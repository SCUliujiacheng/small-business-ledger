def test_failed_write_rolls_back_record_and_request_index(tmp_path, monkeypatch):
    store = Store(tmp_path / "ledger.db")
    insert = store.insert_entry

    def fail_after_insert(conn, validated):
        insert(conn, validated)
        raise LedgerError("test transaction interruption")

    key = str(uuid4())
    monkeypatch.setattr(store, "insert_entry", fail_after_insert)
    with pytest.raises(LedgerError):
        store.create_entry(SALE, key)
    assert store.entries() == []
    monkeypatch.setattr(store, "insert_entry", insert)
    assert store.create_entry(SALE, key)["revenue_cents"] == 100000
    with store.connect() as conn:
        assert conn.execute("SELECT COUNT(*) FROM write_requests").fetchone()[0] == 1


def legacy_database(path):
    """Literal v0 schema, not generated by the current Store implementation."""
    with sqlite3.connect(path) as conn:
        conn.executescript("""
            CREATE TABLE entries (
                id TEXT PRIMARY KEY, kind TEXT NOT NULL, date TEXT NOT NULL,
                description TEXT NOT NULL, category TEXT NOT NULL, quantity INTEGER,
                unit_price_cents INTEGER, unit_cost_cents INTEGER, revenue_cents INTEGER NOT NULL,
                cost_cents INTEGER NOT NULL, amount_cents INTEGER NOT NULL, note TEXT NOT NULL,
                external_id TEXT UNIQUE, created_at TEXT NOT NULL, voided_at TEXT, void_reason TEXT
            );
            CREATE TABLE payments (
                id TEXT PRIMARY KEY, kind TEXT NOT NULL, entry_id TEXT REFERENCES entries(id),
                date TEXT NOT NULL, amount_cents INTEGER NOT NULL, note TEXT NOT NULL,
                created_at TEXT NOT NULL, voided_at TEXT, void_reason TEXT
            );
            CREATE TABLE metadata (key TEXT PRIMARY KEY, value TEXT);
            INSERT INTO entries VALUES ('11111111-1111-4111-8111-111111111111', 'expense', '2026-10-01',
                '旧房租', '房租', NULL, NULL, NULL, 0, 0, 20000, '保留备注', 'old-1',
                '2026-10-01T00:00:00+00:00', NULL, NULL);
            INSERT INTO metadata VALUES ('demo', 'false');
        """)


def test_legacy_upgrade_backs_up_before_migration_and_is_repeatable(tmp_path):
    path = tmp_path / "legacy.db"
    legacy_database(path)
    store = Store(path)
    entry = store.entries()[0]
    assert entry["id"] == "11111111-1111-4111-8111-111111111111"
    assert entry["amount_cents"] == 20000 and entry["note"] == "保留备注"
    assert entry["customer"] == entry["supplier"] == ""
    assert entry["receivable_due_date"] is entry["payable_due_date"] is None
    snapshots = list(tmp_path.glob("legacy.db.backups/ledger-auto-*.json"))
    assert len(snapshots) == 1
    backup = json.loads(snapshots[0].read_text(encoding="utf-8"))
    assert backup["version"] == 1 and backup["entries"][0]["amount_cents"] == 20000
    assert Store(path).entries() == [entry]
    assert len(list(tmp_path.glob("legacy.db.backups/ledger-auto-*.json"))) == 1
    with store.connect() as conn:
        assert conn.execute("PRAGMA user_version").fetchone()[0] == 2


def test_future_schema_is_rejected_without_modification(tmp_path):
    path = tmp_path / "future.db"
