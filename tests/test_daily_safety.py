@pytest.mark.parametrize("failure_point", ["fsync", "replace"])
def test_interrupted_snapshot_publish_preserves_ledger_and_history(
    tmp_path, monkeypatch, failure_point
):
    from small_business_ledger import snapshots

    store = Store(tmp_path / "ledger.db")
    store.create_entry(SALE)
    store.snapshot_now()
    before = store.local_backups()["items"]

    def disk_failure(*args):
        raise OSError("simulated disk failure")

    monkeypatch.setattr(snapshots.os, failure_point, disk_failure)
    with pytest.raises(LedgerError) as error:
        store.create_entry(SALE, str(uuid4()))
    assert error.value.status_code == 503
    assert len(store.entries()) == 1
    assert store.local_backups()["items"] == before
    assert not list((tmp_path / "ledger.db.backups").glob(".pending-*"))
    with store.connect() as conn:
        assert conn.execute("SELECT COUNT(*) FROM write_requests").fetchone()[0] == 0


