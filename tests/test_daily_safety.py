"""Daily-use safety checks against real SQLite files and HTTP routes."""

import json
import sqlite3
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from uuid import uuid4

import pytest
from fastapi.testclient import TestClient

from small_business_ledger.app import create_app
from small_business_ledger.store import LedgerError, Store

SALE = {
    "kind": "sale",
    "date": "2026-10-01",
    "description": "服务",
    "category": "设计",
    "quantity": 1,
    "unit_price": "1000",
    "unit_cost": "100",
}
WRITE = {"X-Ledger-Request": "1"}


def client(path):
    return TestClient(create_app(path), base_url="http://127.0.0.1")


def test_http_replay_creates_one_entry_and_rejects_changed_payload(tmp_path):
    with client(tmp_path / "ledger.db") as api:
        headers = WRITE | {"Idempotency-Key": str(uuid4())}
        first = api.post("/api/entries", json=SALE, headers=headers)
        again = api.post("/api/entries", json=SALE, headers=headers)
        assert first.status_code == again.status_code == 201
        assert first.json()["id"] == again.json()["id"]
        changed = api.post("/api/entries", json=SALE | {"unit_price": "900"}, headers=headers)
        assert changed.status_code == 409
        assert api.get("/api/meta").json()["entry_count"] == 1


def test_payment_retry_survives_restart_void_and_concurrent_requests(tmp_path):
    path = tmp_path / "ledger.db"
    store = Store(path)
    sale = store.create_entry(SALE)
    payload = {"kind": "receipt", "entry_id": sale["id"], "date": "2026-10-02", "amount": "100"}
    key = str(uuid4())
    with ThreadPoolExecutor(max_workers=4) as pool:
        results = list(pool.map(lambda _: Store(path).create_payment(payload, key), range(4)))
    assert len({r["id"] for r in results}) == 1
    assert len(store.payments()) == 1
    assert store.entries()[0]["received_cents"] == 10000
    store.void_payment(results[0]["id"], "录错")
    replay = Store(path).create_payment(payload, key)
    assert replay["id"] == results[0]["id"] and replay["voided_at"]
    assert store.entries()[0]["received_cents"] == 0
    assert len(store.payments()) == 1


def test_request_key_cannot_switch_operation_and_normalized_money_replays(tmp_path):
    store = Store(tmp_path / "ledger.db")
    key = str(uuid4())
    first = store.create_entry(SALE, key)
    assert store.create_entry(SALE | {"unit_price": "1000.00"}, key)["id"] == first["id"]
    with pytest.raises(LedgerError) as failure:
        store.create_payment({"kind": "capital_in", "date": "2026-10-01", "amount": "1"}, key)
    assert failure.value.status_code == 409
    assert store.payments() == []


